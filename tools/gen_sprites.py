#!/usr/bin/env python3
"""Writes the sprite packs and palettes for the knob and the app.

Source: design/sprite_packs.txt (the marks) and PALETTES below.
Output: firmware/src/render/sprites.h and ios/FidgetKnob/SpriteArt.swift.
Run from anywhere: python3 tools/gen_sprites.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# name, white hue (deg), white saturation, accent RGB. "White" is what the
# field is painted in when nothing gives it a colour of its own (a white bulb,
# the clock, music without a cover); the accent is scattered through it.
PALETTES = [
    ("Ember", 32, 0.36, (46, 168, 84)),
    ("Ice", 205, 0.22, (40, 170, 230)),
    ("Sakura", 340, 0.28, (236, 96, 150)),
    ("Mono", 0, 0.0, (150, 150, 150)),
    ("Sunset", 28, 0.62, (150, 90, 230)),
    ("Matrix", 110, 0.30, (40, 230, 110)),
]


def read_packs():
    lines = open(os.path.join(ROOT, "design/sprite_packs.txt")).read().splitlines()
    packs, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("pack "):
            packs.append((line[5:], []))
            i += 1
        elif line.split(" ")[0] in ("heavy", "medium", "light"):
            weight, name = line.split()
            rows = lines[i + 1:i + 10]
            assert all(len(r) == 9 and set(r) <= set(".#") for r in rows), (name, rows)
            packs[-1][1].append((weight, name, rows))
            i += 10
        else:
            i += 1
    for name, sprites in packs:
        assert len(sprites) == 18, name
        for w in ("heavy", "medium", "light"):
            assert sum(1 for s in sprites if s[0] == w) == 6, (name, w)
    return packs


def write_header(packs):
    out = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// GENERATED by tools/gen_sprites.py from design/sprite_packs.txt - edit",
        "// those, not this.",
        "//",
        "// The sprite packs: eighteen 9x9 pixel-art marks each, drawn as text so",
        "// they can be edited by eye ('#' is lit). They come in three weights, and",
        "// the field places them by weight rather than at random: heavy marks pack",
        "// the middle, light ones fray the edge, so the pattern reads as one",
        "// glowing shape instead of as noise.",
        "",
        "namespace sprites {",
        "",
        "constexpr int kSize = 9;",
        "constexpr int kCount = 18;  // Per pack.",
        f"constexpr int kPackCount = {len(packs)};",
        "",
        "enum class Weight : uint8_t { Heavy, Medium, Light };",
        "",
        "struct Sprite {",
        "  Weight weight;",
        "  const char* rows[kSize];",
        "};",
        "",
        "constexpr const char* kPackNames[kPackCount] = {"
        + ", ".join(f'"{n}"' for n, _ in packs) + "};",
        "",
        "// clang-format off",
        "constexpr Sprite kPacks[kPackCount][kCount] = {",
    ]
    for name, sprites in packs:
        out.append(f"  {{  // {name}")
        for w, n, rows in sprites:
            out.append(f"    {{Weight::{w.capitalize()}, {{  // {n}")
            out.append("        " + ", ".join(f'"{r}"' for r in rows) + "}},")
        out.append("  },")
    out += [
        "};",
        "// clang-format on",
        "",
        "// The field's colours when nothing else sets them.",
        "struct Palette {",
        "  const char* name;",
        "  float whiteHue, whiteSaturation;",
        "  uint8_t accentR, accentG, accentB;",
        "};",
        f"constexpr int kPaletteCount = {len(PALETTES)};",
        "constexpr Palette kPalettes[kPaletteCount] = {",
    ]
    for n, h, s, (r, g, b) in PALETTES:
        out.append(f'    {{"{n}", {h:.1f}f, {s:.2f}f, {r}, {g}, {b}}},')
    out += ["};", "", "}  // namespace sprites", ""]
    open(os.path.join(ROOT, "firmware/src/render/sprites.h"), "w").write("\n".join(out))


def write_swift(packs):
    out = [
        "// GENERATED by tools/gen_sprites.py from design/sprite_packs.txt - the",
        "// same marks and palettes the knob draws. Regenerate, do not edit.",
        "",
        "import SwiftUI",
        "",
        "enum SpriteArt {",
        "    enum Weight { case heavy, medium, light }",
        "",
        "    struct Pack {",
        "        let name: String",
        "        let sprites: [(weight: Weight, rows: [String])]",
        "    }",
        "",
        "    struct Palette {",
        "        let name: String",
        "        let white: Color",
        "        let accent: Color",
        "    }",
        "",
        "    static let packs: [Pack] = [",
    ]
    for name, sprites in packs:
        out.append(f'        Pack(name: "{name}", sprites: [')
        for w, n, rows in sprites:
            out.append(f"            (.{w}, [" + ", ".join(f'"{r}"' for r in rows) + "]),")
        out.append("        ]),")
    out += ["    ]", "", "    static let palettes: [Palette] = ["]
    for n, h, s, (r, g, b) in PALETTES:
        out.append(
            f'        Palette(name: "{n}", white: Color(hue: {h / 360:.4f}, saturation: {s:.2f}, brightness: 1),'
            f" accent: Color(red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f})),"
        )
    out += ["    ]", "", "    /// The first pack, kept for callers that predate packs.",
            "    static var sprites: [(weight: Weight, rows: [String])] { packs[0].sprites }", "}", ""]
    open(os.path.join(ROOT, "ios/FidgetKnob/SpriteArt.swift"), "w").write("\n".join(out))


if __name__ == "__main__":
    p = read_packs()
    write_header(p)
    write_swift(p)
    print(f"{len(p)} packs, {len(PALETTES)} palettes written")
